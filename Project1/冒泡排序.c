/*
 * 冒泡排序（升序）
 * 输入 10 个整数，通过相邻元素两两比较并交换完成升序排序。
 * 每轮遍历将当前未排序部分的最大值"冒泡"到末尾。
 * 优化：每轮内层循环长度递减（10 - i - 1），因为末尾元素已就位。
 */
#define _CRT_SECURE_NO_WARNINGS  1
#pragma warning(disable:6031)
#include<stdio.h>
void maopaoapixu()
{
	int i, j, t, a[10];         /* i、j 循环变量，t 交换变量，a 数组 */
	/* 读取 10 个整数 */
	for (i = 0; i < 10; i++)
	{
		printf("请输入第%d个成绩", i + 1);
		scanf("%d", &a[i]);

	}
	/* 冒泡排序核心：外层控制轮数，内层进行相邻比较 */
	for (i = 0; i < 10; i++)
		/* 内层循环范围缩小：已排序的末尾元素不再参与 */
		for (j = 0; j < 10 - i - 1; j++)
			/* 若前一个大于后一个，则交换（升序） */
			if (a[j] > a[j + 1])
			{
				t = a[j]; a[j] = a[j + 1]; a[j + 1] = t;
			}
}