/*
 * 猴子吃桃问题
 * 问题描述：猴子每天吃当前桃子数的一半再加 1 个，到第 10 天早上只剩 1 个。
 * 逆向推导：从第 10 天反推第 1 天的桃子数。
 * 递推公式：前一天 = (当天 + 1) × 2
 * 循环 9 次（第 10 天到第 1 天）得到结果。
 */
#define _CRT_SECURE_NO_WARNINGS  1
#pragma warning(disable:6031)
#include<stdio.h>
int chitao()
{
	int x=1 ,t=0;               /* x: 桃子数，初始为第 10 天的 1 个 */
	/* 逆推 9 天：从第 10 天算到第 1 天 */
	for (; t < 9; t = t + 1)
		x = (x + 1) * 2;        /* 前一天桃子数 = (当天 + 1) × 2 */
	printf("%d", x);
}