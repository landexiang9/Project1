/*
 * 交换排序（降序）
 * 输入 10 个整数，使用交换排序法（选择排序的变体）按降序排列。
 * 核心思想：固定第 i 个元素，依次与后续所有元素比较，
 * 若发现更大的值则交换，确保 a[i] 为当前剩余元素中的最大值。
 */
#include<stdio.h>
int jiaohuanpaixu()
{
	int a[10], i, j, t;         /* a: 存储数组，t: 交换临时变量 */
	printf("请输入10个整数：");
	/* 读取 10 个整数存入数组 */
	for (i = 0; i < 10; i++)
	{
		scanf("%d", &a[i]);
	}
	/* 外层循环：依次确定每个位置的元素 */
	for (i = 0; i < 9; i++)
	{
		/* 内层循环：将 a[i] 与后面所有元素比较 */
		for (j = i+1; j < 10; j++)
		{
			/* 若后面的元素更大，则交换，保证 a[i] 最大 */
			if (a[i] < a[j])
			{
				t = a[i];
				a[i] = a[j];
				a[j] = t;
			}
		}
	}
	/* 输出排序后的降序序列 */
	for  (i=0; i < 10; i++)
	{
		printf("%d ", a[i]);
	}

}