/*
 * 逻辑运算符演示
 * 展示 !（非）、&&（与）、||（或）的运算规则与短路求值特性。
 * 重点：
 *   1. !c：c=0 → !0 = 1（真）
 *   2. 短路求值：!a && !b && c 当 !a=0 时直接短路，不再计算后续
 *   3. 混合运算：c-- || (b==6) && a++，注意运算符优先级：&& 高于 ||
 *   4. 后缀 -- 先取值后递减
 */
#define _CRT_SECURE_NO_WARNINGS  1
#pragma warning(disable:6031)
#include<stdio.h>
int main8()
{int a = 3,b = 3,c = 0,d;
 printf(" %d", !c);                /* !0 = 1，输出 1 */
 printf("%d,", !a && !b && c);     /* !a=0，短路，结果为 0 */
 printf("%d,", !a || !b || c);     /* !a=0, !b=0, c=0 → 0 || 0 = 0, 0 || 0 = 0 */
 printf("%d\n", a >= b && b > c);  /* 3>=3=1, 3>0=1 → 1 && 1 = 1 */
 d = c-- || (b == 6) && a++;       /* c-- 先取 c=0（假），c 变为 -1；短路右侧 &&？实际 && 优先级更高：0 || (0 && a++)，&& 左边为假则短路，a++ 不执行 */
 printf("a=%d,b=%d,c=%d,d=%d\n", a, b, c, d);
 return 0;


}