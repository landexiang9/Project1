/*
 * 星号金字塔
 * 输入行数 n，输出 n 层等腰三角形形状的星号金字塔。
 * 第 i 行有：
 *   前导空格数 = n - i（使星号居中）
 *   星号数    = 2*i - 1（奇数递增）
 * 知识点：双重循环、空格填充、图形输出。
 */
#include<stdio.h>
int jingzita()
{
	int n ,i ,j,k;              /* n: 总行数，i: 当前行，j: 循环变量，k: 空格数 */
	scanf("%d", &n);
	/* 外层循环：控制行数 */
	for (i = 1; i <= n; i++)
	{
		k = n - i;              /* 前导空格数量 */
		/* 输出前导空格 */
		for (j = 1;j<=k;j++)
			{
			printf(" ");
		}
		/* 输出星号：每行 2*i-1 个 */
		for (j = 1; j <= 2 * i - 1; j++)
		{
			printf("*");
		}
		printf("\n");           /* 每行结束换行 */
	}


}