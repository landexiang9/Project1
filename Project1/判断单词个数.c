/*
 * 统计单词个数
 * 输入一个字符串，按空格分隔统计其中包含的单词数量。
 * 算法：遍历字符串，每当遇到一个空格且下一个字符不是空格也不是结束符时，
 * 表示一个单词结束，计数加 1。最后如果第一个字符不是空格，再补加第一个单词。
 */
#include<stdio.h>
void panduandancigeshu()
{
	char str[100];              /* 存储输入的字符串 */
	int i, count = 0;           /* i: 循环变量，count: 单词计数 */
	printf("请输入一个字符串: ");
	gets(str);                  /* 读取一行字符串 */
	/* 遍历字符串直到结束符 */
	for (i = 0; str[i] != '\0'; i++)
	{
		/* 遇到空格且下一个字符不是空格也不是结束符 => 单词分隔 */
		if (str[i] == ' ' && str[i + 1] != ' ' && str[i + 1] != '\0')
		{
			count++;
		}
	}
	/* 如果字符串非空且不以空格开头，则第一个单词未计入，需补加 */
	if (i > 0 && str[0] != ' ')
	{
		count++;
	}
	printf("单词的个数为: %d\n", count);
}
