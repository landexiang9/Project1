/*
 * 杨辉三角（帕斯卡三角形）
 * 打印 6 行杨辉三角，每行的首尾元素为 1，中间元素等于上一行相邻两数之和。
 * 递推公式：a[t][i] = a[t-1][i-1] + a[t-1][i]
 * 知识点：二维数组、双重循环、组合数性质。
 */
#include <stdio.h>

int yanghuishanjiao()
{
    int a[6][6], i, t;         /* a: 存储三角数值，t: 行，i: 列 */
    /* 构造杨辉三角 */
    for (t = 0; t < 6; t++) {
        a[t][0] = 1;            /* 每行第一个元素为 1 */
        a[t][t] = 1;            /* 每行最后一个元素为 1 */
        /* 中间元素由上一行相邻两个元素相加得到 */
        for (i = 1; i < t; i++) {
            a[t][i] = a[t - 1][i - 1] + a[t - 1][i];
        }
    }

    /* 输出杨辉三角 */
    for (t = 0; t < 6; t++) {
        for (i = 0; i <= t; i++) {
            printf("%d ", a[t][i]);
        }
        printf("\n");
    }
    return 0;
}