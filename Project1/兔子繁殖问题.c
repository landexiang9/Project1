/*
 * 兔子繁殖问题（斐波那契数列）
 * 经典问题：每对兔子每月生一对新兔，新兔第二个月起开始繁殖。
 * 第 n 个月的兔子对数 = 第 n-1 个月对数 + 第 n-2 个月对数。
 * 种子值：a=0（初始）, b=1（第一个月），迭代递推输出每个月结果。
 */
#include<stdio.h>
int tuzhifanzi()
{
	int a=0, b=1, c,n,m;        /* a: 前两个月前，b: 前一个月，c: 当前月 */
	printf("请输入兔子繁殖的月数:");
	scanf("%d",&n);
	/* 从第 1 个月循环到第 n 个月 */
	for (m = 1; m <= n; m++)
	{
		c = a + b;              /* 当前月对数 = 前两个月之和 */
		a = b;                  /* 向前滚动：a 更新为前一个月 */
		b = c;                  /* b 更新为当前月 */
		printf("第%d个月份", m);
		printf("%d只\n", c);    /* 输出该月兔子对数 */
	}

	

}